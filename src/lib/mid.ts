export interface MidFlag {
  code: string;
  country: string;
}

export function flagFromMmsi(mmsi: number | null | undefined): MidFlag | null {
  if (!mmsi) return null;
  const s = String(mmsi);
  if (s.length !== 9) return null;
  const hit = MID[s.slice(0, 3)];
  return hit ? { code: hit[0], country: hit[1] } : null;
}
